export type MessageKey = keyof typeof zhTW;
const messages: Record<Locale, Record<MessageKey, string>> = { 'zh-TW': zhTW, en };

const LOCALE_KEY = 'edgedock.locale';
export const locale = ref<Locale>((localStorage.getItem(LOCALE_KEY) as Locale) || 'zh-TW');

export function setLocale(l: Locale, persist = true) {
  locale.value = l;
  document.documentElement.lang = l === 'zh-TW' ? 'zh-Hant-TW' : 'en';
  if (persist) localStorage.setItem(LOCALE_KEY, l);
}

/** Apply the server's default language unless the user picked one. */
export function applyDefaultLocale(l: Locale) {
  if (!localStorage.getItem(LOCALE_KEY)) setLocale(l, false);
}

export function t(key: MessageKey, params?: Record<string, string | number>): string {
  let s = messages[locale.value][key] ?? zhTW[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}
